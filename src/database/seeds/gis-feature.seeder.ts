export class GisFeatureSeeder {
  constructor(private readonly dataSource: DataSource) {}

  async run(): Promise<void> {
    const repo = this.dataSource.getRepository(GisFeatureEntity);

    const existing = await repo.count();
    if (existing > 0) {
      console.log(`Skipping seed: ${existing} features already exist.`);
      return;
    }

    const entities = SEED_FEATURES.map((f) =>
      repo.create({
        name: f.name,
        color: f.color,
        featureType: f.featureType,
        geometry: {
          type: 'Polygon',
          coordinates: f.coordinates,
        },
        properties: {
          name: f.name,
          color: f.color,
          featureType: f.featureType,
        },
      })
    );

    await repo.save(entities);
    console.log(`Seeded ${entities.length} GIS features for Şağan/Buzovna area.`);
  }
}
